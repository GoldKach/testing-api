async function main() {
  console.log("Looking up AAPL asset...");

  const aapl = await db.asset.findFirst({ where: { symbol: "AAPL" } });
  if (!aapl) {
    console.error("AAPL asset not found.");
    process.exit(1);
  }

  console.log(`Found AAPL — id: ${aapl.id}`);
  console.log(`Upserting ${AAPL.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of AAPL) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: aapl.id, priceDate } },
        update: { closePrice },
        create: { assetId: aapl.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${AAPL.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
