async function main() {
  console.log("Looking up NVDA asset...");

  const nvda = await db.asset.findFirst({ where: { symbol: "NVDA" } });
  if (!nvda) {
    console.error("NVDA asset not found.");
    process.exit(1);
  }

  console.log(`Found NVDA — id: ${nvda.id}`);
  console.log(`Upserting ${NVDA.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of NVDA) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: nvda.id, priceDate } },
        update: { closePrice },
        create: { assetId: nvda.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${NVDA.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
