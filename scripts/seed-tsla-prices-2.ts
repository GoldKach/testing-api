async function main() {
  console.log("Looking up TSLA asset...");

  const tsla = await db.asset.findFirst({ where: { symbol: "TSLA" } });
  if (!tsla) {
    console.error("TSLA asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found TSLA — id: ${tsla.id}`);
  console.log(`Upserting ${TSLA.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of TSLA) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: tsla.id, priceDate } },
        update: { closePrice },
        create: { assetId: tsla.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${TSLA.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
