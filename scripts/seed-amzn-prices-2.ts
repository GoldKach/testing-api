async function main() {
  console.log("Looking up AMZN asset...");

  const amzn = await db.asset.findFirst({ where: { symbol: "AMZN" } });
  if (!amzn) {
    console.error("AMZN asset not found.");
    process.exit(1);
  }

  console.log(`Found AMZN — id: ${amzn.id}`);
  console.log(`Upserting ${AMZN.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of AMZN) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: amzn.id, priceDate } },
        update: { closePrice },
        create: { assetId: amzn.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${AMZN.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
