async function main() {
  console.log("Looking up GOOGL asset...");

  const googl = await db.asset.findFirst({ where: { symbol: "GOOGL" } });
  if (!googl) {
    console.error("GOOGL asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found GOOGL — id: ${googl.id}`);
  console.log(`Upserting ${GOOGL.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of GOOGL) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: googl.id, priceDate } },
        update: { closePrice },
        create: { assetId: googl.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${GOOGL.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
