async function main() {
  console.log("Looking up MSFT asset...");

  const msft = await db.asset.findFirst({ where: { symbol: "MSFT" } });
  if (!msft) {
    console.error("MSFT asset not found.");
    process.exit(1);
  }

  console.log(`Found MSFT — id: ${msft.id}`);
  console.log(`Upserting ${MSFT.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of MSFT) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: msft.id, priceDate } },
        update: { closePrice },
        create: { assetId: msft.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${MSFT.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
