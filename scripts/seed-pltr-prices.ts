async function main() {
  console.log("Looking up PLTR asset...");

  const pltr = await db.asset.findFirst({ where: { symbol: "PLTR" } });
  if (!pltr) {
    console.error("PLTR asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found PLTR — id: ${pltr.id}`);
  console.log(`Upserting ${PLTR.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of PLTR) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: pltr.id, priceDate } },
        update: { closePrice },
        create: { assetId: pltr.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${PLTR.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
