async function main() {
  console.log("Looking up SCHD asset...");

  const schd = await db.asset.findFirst({ where: { symbol: "SCHD" } });
  if (!schd) {
    console.error("SCHD asset not found.");
    process.exit(1);
  }

  console.log(`Found SCHD — id: ${schd.id}`);
  console.log(`Upserting ${SCHD.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of SCHD) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: schd.id, priceDate } },
        update: { closePrice },
        create: { assetId: schd.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${SCHD.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
