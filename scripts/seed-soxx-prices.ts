const ALL_RECORDS = [...SOXX_2024, ...SOXX_2025, ...SOXX_2026];

async function main() {
  console.log("Looking up SOXX asset...");

  const soxx = await db.asset.findFirst({ where: { symbol: "SOXX" } });
  if (!soxx) {
    console.error("SOXX asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found SOXX — id: ${soxx.id}`);
  console.log(`Upserting ${ALL_RECORDS.length} price records (2024 + 2025 + 2026)...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of ALL_RECORDS) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: soxx.id, priceDate } },
        update: { closePrice },
        create: { assetId: soxx.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${ALL_RECORDS.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);

  // Update live closePrice to the latest 2026 value
  await db.asset.update({
    where: { id: soxx.id },
    data:  { closePrice: 491.46 },
  });
  console.log("Live closePrice confirmed at $491.46 (Jul 28, 2026).");
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
