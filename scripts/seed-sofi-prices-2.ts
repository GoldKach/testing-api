async function main() {
  console.log("Looking up SOFI asset...");

  const sofi = await db.asset.findFirst({ where: { symbol: "SOFI" } });
  if (!sofi) {
    console.error("SOFI asset not found.");
    process.exit(1);
  }

  console.log(`Found SOFI — id: ${sofi.id}`);
  console.log(`Upserting ${SOFI.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of SOFI) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: sofi.id, priceDate } },
        update: { closePrice },
        create: { assetId: sofi.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${SOFI.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
