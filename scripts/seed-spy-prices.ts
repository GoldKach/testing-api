async function main() {
  console.log("Looking up SPY asset...");

  const spy = await db.asset.findFirst({ where: { symbol: "SPY" } });
  if (!spy) {
    console.error("SPY asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found SPY — id: ${spy.id}`);
  console.log(`Upserting ${SPY.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of SPY) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: spy.id, priceDate } },
        update: { closePrice },
        create: { assetId: spy.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${SPY.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
