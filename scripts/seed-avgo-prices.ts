async function main() {
  console.log("Looking up AVGO asset...");

  const avgo = await db.asset.findFirst({ where: { symbol: "AVGO" } });
  if (!avgo) {
    console.error("AVGO asset not found. Create it in the admin dashboard first.");
    process.exit(1);
  }

  console.log(`Found AVGO — id: ${avgo.id}`);
  console.log(`Upserting ${AVGO.length} price records...`);

  let success = 0;
  let failed  = 0;

  for (const [dateStr, closePrice] of AVGO) {
    const priceDate = new Date(dateStr + "T00:00:00.000Z");
    try {
      await db.assetPriceHistory.upsert({
        where:  { assetId_priceDate: { assetId: avgo.id, priceDate } },
        update: { closePrice },
        create: { assetId: avgo.id, priceDate, closePrice },
      });
      success++;
      process.stdout.write(`\r  ${success}/${AVGO.length} saved...`);
    } catch (err: any) {
      failed++;
      console.error(`\n  Failed ${dateStr}: ${err?.message}`);
    }
  }

  console.log(`\n\nDone. ${success} upserted, ${failed} failed.`);
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => db.$disconnect());
